CREATE TABLE IF NOT EXISTS zonas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL UNIQUE,
  logo_url VARCHAR(500),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS destinos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL UNIQUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS roles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(30) NOT NULL UNIQUE,
  nombre VARCHAR(80) NOT NULL,
  logo_url VARCHAR(500),
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  "user" VARCHAR(60) NOT NULL UNIQUE,
  dni VARCHAR(20) NOT NULL,
  telefono VARCHAR(30),
  zona VARCHAR(80),
  destino_id INTEGER REFERENCES destinos(id) ON DELETE SET NULL ON UPDATE CASCADE,
  pass VARCHAR(120) NOT NULL,
  rol VARCHAR(30) NOT NULL DEFAULT 'operador'
    CHECK (rol IN ('admin', 'admin_aduana', 'admin_defiba', 'admin_transito', 'operador', 'pase', 'defiba', 'aduana')),
  logo_url VARCHAR(500),
  fondo_url VARCHAR(500),
  tema_preferido VARCHAR(30) NOT NULL DEFAULT 'oscuro'
    CHECK (tema_preferido IN ('oscuro', 'claro', 'azul_marino', 'azul_claro')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pase_libre_estado (
  id SMALLINT PRIMARY KEY CHECK (id = 1),
  activo BOOLEAN NOT NULL DEFAULT FALSE,
  actualizado_por INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT INTO pase_libre_estado (id, activo)
VALUES (1, FALSE)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS camioneros (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  dni VARCHAR(20) NOT NULL UNIQUE,
  patente VARCHAR(20) NOT NULL,
  telefono VARCHAR(30),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_camioneros_patente ON camioneros (patente);

CREATE TABLE IF NOT EXISTS turnos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero INTEGER,
  camionero_id INTEGER NOT NULL REFERENCES camioneros(id) ON DELETE CASCADE ON UPDATE CASCADE,
  patente VARCHAR(20) NOT NULL,
  empresa VARCHAR(120),
  mercaderia TEXT,
  mercaderia_vacia BOOLEAN NOT NULL DEFAULT FALSE,
  fecha_ingreso DATE NOT NULL DEFAULT CURRENT_DATE,
  hora_ingreso TIME NOT NULL DEFAULT LOCALTIME,
  estado VARCHAR(30) NOT NULL DEFAULT 'pendiente'
    CHECK (estado IN ('pendiente', 'en_curso', 'finalizado', 'reservado', 'listo_para_salir', 'anulado')),
  origen VARCHAR(20) NOT NULL DEFAULT 'normal',
  numero_operacion VARCHAR(80),
  prioridad VARCHAR(20),
  usuario_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL ON UPDATE CASCADE,
  usuario_pase_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL ON UPDATE CASCADE,
  zona_id INTEGER NOT NULL REFERENCES zonas(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  destino_id INTEGER REFERENCES destinos(id) ON DELETE SET NULL ON UPDATE CASCADE,
  aduana_confirmado BOOLEAN NOT NULL DEFAULT FALSE,
  aduana_confirmado_en TIMESTAMPTZ,
  estado_aduana VARCHAR(20),
  defiba_aviso_confirmado BOOLEAN NOT NULL DEFAULT FALSE,
  operador_aduana_aviso_confirmado BOOLEAN NOT NULL DEFAULT FALSE,
  bocina_pendiente BOOLEAN NOT NULL DEFAULT FALSE,
  bocina_pendiente_en TIMESTAMPTZ,
  bocina_procesando BOOLEAN NOT NULL DEFAULT FALSE,
  bocina_reclamada_en TIMESTAMPTZ,
  creada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_turnos_zona_numero UNIQUE (zona_id, numero)
);
CREATE INDEX IF NOT EXISTS idx_turnos_patente ON turnos (patente);
CREATE INDEX IF NOT EXISTS idx_turnos_camionero_estado ON turnos (camionero_id, estado);
CREATE INDEX IF NOT EXISTS idx_turnos_estado_fecha ON turnos (estado, fecha_ingreso, hora_ingreso);
CREATE INDEX IF NOT EXISTS idx_turnos_zona_estado_fecha ON turnos (zona_id, estado, fecha_ingreso, hora_ingreso);
CREATE INDEX IF NOT EXISTS idx_turnos_estado_numero ON turnos (estado, numero);
CREATE INDEX IF NOT EXISTS idx_turnos_numero ON turnos (numero);
CREATE INDEX IF NOT EXISTS idx_turnos_bocina_queue ON turnos (bocina_pendiente_en, id)
  WHERE bocina_pendiente = TRUE AND bocina_procesando = FALSE AND aduana_confirmado = TRUE
    AND estado NOT IN ('finalizado', 'anulado');

CREATE TABLE IF NOT EXISTS turno_historial (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  turno_id INTEGER NOT NULL REFERENCES turnos(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  zona_id INTEGER NOT NULL REFERENCES zonas(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  estado VARCHAR(30) NOT NULL
    CHECK (estado IN ('pendiente', 'en_curso', 'finalizado', 'reservado', 'listo_para_salir', 'anulado')),
  evento VARCHAR(30) NOT NULL DEFAULT 'estado',
  usuario_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL ON UPDATE CASCADE,
  origen VARCHAR(30) NOT NULL DEFAULT 'sistema',
  registrado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_historial_turno_fecha ON turno_historial (turno_id, registrado_en);
CREATE INDEX IF NOT EXISTS idx_historial_zona_estado ON turno_historial (zona_id, estado, registrado_en);
CREATE INDEX IF NOT EXISTS idx_historial_evento_turno ON turno_historial (evento, turno_id);

CREATE TABLE IF NOT EXISTS cargas_especiales (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patente VARCHAR(20) NOT NULL,
  zona_id INTEGER NOT NULL REFERENCES zonas(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  destino_id INTEGER NOT NULL REFERENCES destinos(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  estado VARCHAR(20) NOT NULL DEFAULT 'en_camino'
    CHECK (estado IN ('en_camino', 'finalizado')),
  usuario_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL ON UPDATE CASCADE,
  creada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_cargas_especiales_zona_estado_fecha
  ON cargas_especiales (zona_id, estado, creada_en);

CREATE TABLE IF NOT EXISTS qr_tokens (
  token CHAR(32) PRIMARY KEY,
  zona_id INTEGER NOT NULL REFERENCES zonas(id) ON DELETE CASCADE ON UPDATE CASCADE,
  expires_at BIGINT NOT NULL,
  used BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  claimed_at TIMESTAMPTZ,
  used_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS chat_sessions (
  token_hash CHAR(64) PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at TIMESTAMPTZ NOT NULL,
  revoked_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_chat_sessions_user ON chat_sessions (usuario_id, expires_at);

CREATE TABLE IF NOT EXISTS chat_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  recipient_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  content VARCHAR(2000) NOT NULL CHECK (length(btrim(content)) > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  delivered_at TIMESTAMPTZ,
  read_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_chat_messages_conversation
  ON chat_messages (sender_id, recipient_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_chat_messages_unread
  ON chat_messages (recipient_id, sender_id, id DESC) WHERE read_at IS NULL;