function normalizeSql(sql) {
  let normalized = sql
    .replace(/"([A-Za-z_][A-Za-z0-9_]*)"/g, '`$1`')
    .replace(/\bILIKE\b/gi, 'LIKE')
    .replace(/\bBTRIM\s*\(/gi, 'TRIM(')
    .replace(/\bFOR\s+UPDATE\s+OF\s+[A-Za-z_][A-Za-z0-9_]*/gi, 'FOR UPDATE')
    .replace(/::[A-Za-z_][A-Za-z0-9_]*(?:\[\])?/g, '')
    .replace(
      /CURRENT_TIMESTAMP\s*\+\s*\(\s*(\$\d+)\s*\*\s*INTERVAL\s*'1 day'\s*\)/gi,
      'DATE_ADD(CURRENT_TIMESTAMP, INTERVAL $1 DAY)',
    )
    .replace(
      /CURRENT_TIMESTAMP\s*-\s*INTERVAL\s*'(\d+)\s+(minutes?|hours?|days?)'/gi,
      (_match, count, unit) => `DATE_SUB(CURRENT_TIMESTAMP, INTERVAL ${count} ${unit.toUpperCase().replace(/S$/, '')})`,
    );

  const conflictNothing = /ON\s+CONFLICT(?:\s*\([^)]*\))?\s+DO\s+NOTHING/gi;
  if (conflictNothing.test(normalized)) {
    normalized = normalized.replace(conflictNothing, '');
    normalized = normalized.replace(/^\s*INSERT\s+INTO\b/i, 'INSERT IGNORE INTO');
  }
  normalized = normalized.replace(
    /ON\s+CONFLICT\s*\([^)]*\)\s+DO\s+UPDATE\s+SET/gi,
    'ON DUPLICATE KEY UPDATE',
  );
  normalized = normalized.replace(/\bEXCLUDED\.([A-Za-z_][A-Za-z0-9_]*)/gi, 'VALUES($1)');
  return normalized;
}

export function compileMysqlQuery(sql, values = []) {
  const normalized = normalizeSql(sql);
  const arrayMarker = /([A-Za-z_][A-Za-z0-9_.]*)\s*=\s*ANY\s*\(\s*\$(\d+)(?::[A-Za-z_][A-Za-z0-9_]*\[\])?\s*\)/gi;
  const expanded = normalized.replace(arrayMarker, (_match, column, indexText) => {
    const array = values[Number(indexText) - 1];
    if (!Array.isArray(array)) {
      throw new TypeError(`El parámetro $${indexText} de ANY debe ser un arreglo.`);
    }
    if (array.length === 0) return `${column} IN (NULL)`;
    return `${column} IN (${array.map((_, index) => `__array_${indexText}_${index}__`).join(', ')})`;
  });

  const parameters = [];
  const statement = expanded.replace(/\$(\d+)|__array_(\d+)_(\d+)__/g, (_match, index, arrayIndex, elementIndex) => {
    if (index) {
      const position = Number(index) - 1;
      if (position < 0 || position >= values.length) {
        throw new RangeError(`Falta el parámetro $${index} de la consulta.`);
      }
      parameters.push(values[position]);
    } else {
      const array = values[Number(arrayIndex) - 1];
      parameters.push(array[Number(elementIndex)]);
    }
    return '?';
  });

  return { sql: statement, values: parameters };
}

function splitStatements(sql) {
  return sql
    .split(';')
    .map((statement) => statement.trim())
    .filter(Boolean);
}

function translateDdl(sql) {
  if (/^\s*ALTER\s+TABLE\s+usuarios\s+(?:DROP\s+CONSTRAINT\s+IF\s+EXISTS|ADD\s+CONSTRAINT)\s+usuarios_rol_check\b/i.test(sql)) {
    return '';
  }
  let translated = sql
    .replace(/GENERATED BY DEFAULT AS IDENTITY/gi, 'AUTO_INCREMENT')
    .replace(/\bTIMESTAMPTZ\b/gi, 'DATETIME(3)')
    .replace(/\bBOOLEAN\b/gi, 'TINYINT(1)')
    .replace(/\bINTEGER\b/gi, 'INT')
    .replace(/CREATE\s+(UNIQUE\s+)?INDEX\s+IF\s+NOT\s+EXISTS/gi, 'CREATE $1INDEX');
  if (/^\s*CREATE\s+(?:UNIQUE\s+)?INDEX\b/i.test(translated)) {
    translated = translated.replace(/\s+WHERE\s+[^;]+$/i, '');
  }
  return translated;
}

function mapMysqlError(error) {
  if (error.code === 'ER_DUP_ENTRY') error.code = '23505';
  if (error.code === 'ER_NO_REFERENCED_ROW_2' || error.code === 'ER_ROW_IS_REFERENCED_2') {
    error.code = '23503';
  }
  return error;
}

function adaptResult(result) {
  if (Array.isArray(result)) {
    return { rows: result, rowCount: result.length };
  }
  return {
    rows: [],
    rowCount: result.affectedRows ?? 0,
    insertId: result.insertId,
    command: result.command,
  };
}

export function createMysqlPoolAdapter(mysqlPool) {
  async function runQuery(connection, sql, values = []) {
    const statements = values.length ? [sql] : splitStatements(sql);
    let adapted;
    for (const statement of statements) {
      if (!statement) continue;
      const indexMatch = statement.match(
        /^\s*CREATE\s+(?:UNIQUE\s+)?INDEX\s+IF\s+NOT\s+EXISTS\s+`?([A-Za-z_][A-Za-z0-9_]*)`?\s+ON\s+`?([A-Za-z_][A-Za-z0-9_]*)`?/i,
      );
      if (indexMatch) {
        const [existing] = await mysqlPool.query(
          `SELECT 1 FROM information_schema.statistics
           WHERE table_schema = DATABASE() AND table_name = ? AND index_name = ? LIMIT 1`,
          [indexMatch[2], indexMatch[1]],
        );
        if (existing.length) continue;
      }

      const translated = translateDdl(statement);
      if (!translated.trim()) continue;
      const compiled = compileMysqlQuery(translated, values);
      try {
        const [result] = await connection.query(compiled.sql, compiled.values);
        adapted = adaptResult(result);
      } catch (error) {
        throw mapMysqlError(error);
      }
    }
    return adapted || { rows: [], rowCount: 0 };
  }

  return {
    query: (sql, values) => runQuery(mysqlPool, sql, values),
    async connect() {
      const connection = await mysqlPool.getConnection();
      return {
        query: (sql, values) => runQuery(connection, sql, values),
        release: () => connection.release(),
      };
    },
    end: () => mysqlPool.end(),
    on: (...args) => mysqlPool.on(...args),
  };
}
