import test from 'node:test';
import assert from 'node:assert/strict';
import { compileMysqlQuery, createMysqlPoolAdapter } from '../src/mysql-dialect.js';

test('compiles PostgreSQL positional placeholders in the correct order', () => {
  const compiled = compileMysqlQuery(
    'SELECT * FROM usuarios WHERE id = $2 AND rol = $1 AND zona = $2',
    ['operador', 17],
  );
  assert.deepEqual(compiled, {
    sql: 'SELECT * FROM usuarios WHERE id = ? AND rol = ? AND zona = ?',
    values: [17, 'operador', 17],
  });
});

test('expands array comparisons and preserves values after the array', () => {
  const compiled = compileMysqlQuery(
    'SELECT id FROM turnos WHERE id = ANY($1::int[]) AND estado = $2',
    [[4, 8, 15], 'reservado'],
  );
  assert.deepEqual(compiled, {
    sql: 'SELECT id FROM turnos WHERE id IN (?, ?, ?) AND estado = ?',
    values: [4, 8, 15, 'reservado'],
  });
});

test('compiles empty array comparisons to a match-nothing predicate', () => {
  const compiled = compileMysqlQuery(
    'SELECT id FROM turnos WHERE id = ANY($1::int[])',
    [[]],
  );
  assert.deepEqual(compiled, {
    sql: 'SELECT id FROM turnos WHERE id IN (NULL)',
    values: [],
  });
});

test('translates conflict updates, case-insensitive search and PostgreSQL casts', () => {
  const compiled = compileMysqlQuery(
    `INSERT INTO pase_libre_destinos (destino_id, activo)
     VALUES ($1, $2)
     ON CONFLICT (destino_id) DO UPDATE SET activo = EXCLUDED.activo
     RETURNING activo`,
    [5, true],
  );
  assert.equal(
    compiled.sql,
    `INSERT INTO pase_libre_destinos (destino_id, activo)
     VALUES (?, ?)
     ON DUPLICATE KEY UPDATE activo = VALUES(activo)
     RETURNING activo`,
  );
  assert.deepEqual(compiled.values, [5, true]);

  const search = compileMysqlQuery('SELECT id FROM camioneros WHERE nombre ILIKE $1::varchar', ['%ana%']);
  assert.deepEqual(search, {
    sql: 'SELECT id FROM camioneros WHERE nombre LIKE ?',
    values: ['%ana%'],
  });
  assert.equal(compileMysqlQuery('SELECT BTRIM(nombre) FROM usuarios').sql, 'SELECT TRIM(nombre) FROM usuarios');
});

test('translates PostgreSQL interval expressions to MariaDB date arithmetic', () => {
  const compiled = compileMysqlQuery(
    `SELECT CURRENT_TIMESTAMP + ($1 * INTERVAL '1 day'),
            CURRENT_TIMESTAMP - INTERVAL '10 minutes'`,
    [30],
  );
  assert.deepEqual(compiled, {
    sql: `SELECT DATE_ADD(CURRENT_TIMESTAMP, INTERVAL ? DAY),
            DATE_SUB(CURRENT_TIMESTAMP, INTERVAL 10 MINUTE)`,
    values: [30],
  });
});

test('preserves WHERE clauses while executing regular SELECT statements', async () => {
  const statements = [];
  const mysqlPool = {
    async query(sql, values) {
      statements.push({ sql, values });
      return [[{ id: 1 }], []];
    },
    async end() {},
    on() {},
  };
  const pool = createMysqlPoolAdapter(mysqlPool);
  const result = await pool.query('SELECT id FROM usuarios WHERE id = $1', [1]);

  assert.deepEqual(statements, [{
    sql: 'SELECT id FROM usuarios WHERE id = ?',
    values: [1],
  }]);
  assert.deepEqual(result, { rows: [{ id: 1 }], rowCount: 1 });
});

test('translates PostgreSQL table and partial-index definitions for MariaDB', async () => {
  const statements = [];
  const mysqlPool = {
    async query(sql, values) {
      statements.push({ sql, values });
      if (sql.includes('information_schema.statistics')) return [[], []];
      return [{ affectedRows: 0 }, []];
    },
    async end() {},
    on() {},
  };
  const pool = createMysqlPoolAdapter(mysqlPool);
  await pool.query(`CREATE TABLE IF NOT EXISTS sample (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL
  );
  CREATE INDEX IF NOT EXISTS idx_sample ON sample (id) WHERE id > 0;`);

  assert.equal(statements.length, 3);
  assert.match(statements[0].sql, /id INT AUTO_INCREMENT PRIMARY KEY/);
  assert.match(statements[0].sql, /created_at DATETIME\(3\)/);
  assert.equal(statements[2].sql, 'CREATE INDEX idx_sample ON sample (id)');
});
